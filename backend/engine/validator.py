import json
import os

class KnowledgeValidator:
    def __init__(self, base_path="knowledge"):
        self.base_path = base_path
        self.questions = self._load("questions.json")
        self.rules = self._load("rules.json")
        self.paths = self._load("paths.json")

    def _load(self, filename):
        path = os.path.join(self.base_path, filename)
        if not os.path.exists(path):
            return {}
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)

    def validate_all(self):
        print("--- Starting Knowledge Validation ---")
        self._validate_questions()
        self._validate_rules()
        self._validate_paths()
        print("--- Validation Complete ---")

    def _validate_questions(self):
        print("Validating Questions...")
        for q_id, q_data in self.questions.items():
            if "options" not in q_data:
                print(f"[Warning] Question {q_id} has no options.")
            else:
                for idx, opt in enumerate(q_data["options"]):
                    if "modifiers" not in opt or not opt["modifiers"]:
                        # END node options might not have modifiers, but ideally they do.
                        if opt.get("next") != "END":
                            print(f"[Warning] Question {q_id} Option {idx} ('{opt.get('text')}') has NO modifiers!")

    def _validate_rules(self):
        print("Validating Rules...")
        all_attributes_in_rules = set()
        for rule in self.rules:
            if "RuleID" not in rule:
                print(f"[Error] A rule is missing RuleID.")
            
            # Check conditions
            conds = rule.get("Conditions", {})
            if not conds:
                print(f"[Error] Rule {rule.get('RuleID')} has no conditions.")
            for attr in conds:
                all_attributes_in_rules.add(attr)
                
            # Check scores
            scores = rule.get("ScoreChanges", {})
            if not scores:
                print(f"[Error] Rule {rule.get('RuleID')} has no score changes.")

        # Find attributes in questions that are never used in rules
        all_attributes_in_questions = set()
        for q in self.questions.values():
            for opt in q.get("options", []):
                for attr in opt.get("modifiers", {}):
                    all_attributes_in_questions.add(attr)

        unused_attrs = all_attributes_in_questions - all_attributes_in_rules
        if unused_attrs:
            print(f"[Warning] Attributes generated by questions but NEVER used in rules: {unused_attrs}")

    def _validate_paths(self):
        print("Validating Paths...")
        path_names = {p["name"] for p in self.paths}
        
        # Check if every path is affected by at least one rule
        paths_in_rules = set()
        for rule in self.rules:
            for p in rule.get("ScoreChanges", {}):
                paths_in_rules.add(p)
                
        unaffected_paths = path_names - paths_in_rules
        if unaffected_paths:
            print(f"[Error] Paths never affected by any rule: {unaffected_paths}")
            
if __name__ == "__main__":
    import sys
