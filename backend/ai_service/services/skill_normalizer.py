    @classmethod
    def normalize(cls, skill: str) -> str:
        """
        Convert a raw skill string into its canonical form.
        """
        if not skill or not isinstance(skill, str):
            return ""
        s = skill.lower().strip()
        # Remove common suffixes/prefixes noise
        s = re.sub(r"[®™©]", "", s)
        s = re.sub(r"\s*\(.*\)", "", s)  # remove parenthetical notes
        s = s.replace("/", " ").replace("-", " ").replace("_", " ")
        s = re.sub(r"\s+", " ", s).strip()
        return cls.ALIASES.get(s, s)

    @classmethod
    def parse(cls, raw) -> frozenset:
        """
        Convert any raw skill input into a frozenset of canonical skills.
        Handles: list, tuple, comma-string, JSON string, None.
        """
        if not raw:
            return frozenset()
        if isinstance(raw, (list, tuple, set)):
            items = raw
        elif isinstance(raw, str):
            raw = raw.strip()
            if raw.startswith("["):
                try:
                    items = json.loads(raw)
                except Exception:
                    items = raw.strip("[]").split(",")
            else:
                items = raw.split(",")
        else:
            return frozenset()

        normalized = set()
        for item in items:
            if not item or not isinstance(item, str):
                continue
            can = cls.normalize(item)
            if can and can != "general":
                normalized.add(can)
        return frozenset(normalized)

    @classmethod
    def overlap(cls, user_skills: frozenset, job_skills: frozenset) -> float:
        """
        Compute Jaccard-like overlap: |intersection| / |union|.
        Returns 0.0 if either set is empty, but caller may override to np.nan.
        """
        union = user_skills | job_skills
        if not union:
            return 0.0
        return len(user_skills & job_skills) / len(union)